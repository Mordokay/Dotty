#!/usr/bin/env python3
"""The Companion's packs for the SD card (cartridges/companion/assets/*.bin, made by
tools/avatar_art.py and tools/build_voice_pack.py) and the header that tells the firmware which
ones it wants (cartridges/companion/assets_manifest.h: per pack its fingerprinted file name, size
and SHA-256). Releases and the bench server publish each pack as companion-<stem>-<sha8>.bin;
the Companion downloads them into its data folder (spec:
docs/superpowers/specs/2026-11-03-companion-make-room-design.md).

    python3 tools/companion_assets.py            # rewrite the manifest from the packs
    python3 tools/companion_assets.py --check    # exit 1 if the manifest is stale
    python3 tools/companion_assets.py --name avatars   # print a pack's fingerprinted name
"""
import argparse
import hashlib
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
ASSETS = REPO / "cartridges/companion/assets"
MANIFEST = REPO / "cartridges/companion/assets_manifest.h"


def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def fingerprint_name(path):
    return f"companion-{path.stem}-{sha256(path)[:8]}.bin"


def packs():
    return sorted(ASSETS.glob("*.bin"))


def manifest_text():
    lines = ["// Generated by tools/companion_assets.py — edit the packs, not this.", "#pragma once", "",
             "#include <stdint.h>", "",
             "// A pack the Companion downloads to its data folder (assets/<stem>.bin in the repo).",
             "struct AssetPack {", "  const char *stem;    // \"avatars\", \"voices\"",
             "  const char *file;    // its name on releases: companion-<stem>-<sha8>.bin", "  uint32_t size;",
             "  const char *sha256;  // 64 hex digits", "};", "", "constexpr AssetPack kAssetPacks[] = {"]
    for p in packs():
        lines.append(f'    {{"{p.stem}", "{fingerprint_name(p)}", {p.stat().st_size}, "{sha256(p)}"}},')
    lines += ["};", "constexpr int kAssetPackCount = sizeof(kAssetPacks) / sizeof(kAssetPacks[0]);", ""]
    return "\n".join(lines)


def write_manifest():
    MANIFEST.write_text(manifest_text())
    print(f"{len(packs())} packs -> {MANIFEST.relative_to(REPO)}")


def check_manifest():
    """True when the manifest matches the packs on disk."""
    return MANIFEST.exists() and MANIFEST.read_text() == manifest_text()


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--name")
    args = parser.parse_args()
    if args.name:
        print(fingerprint_name(ASSETS / f"{args.name}.bin"))
    elif args.check:
        if not check_manifest():
            sys.exit("assets_manifest.h is stale: run tools/avatar_art.py / tools/build_voice_pack.py")
        print("manifest up to date")
    else:
        write_manifest()


if __name__ == "__main__":
    main()
