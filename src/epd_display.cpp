// GFXcanvas1 stores pixels MSB-first, 25 bytes per row, 1 = set: the same layout
// the controller RAM uses with 1 = white, so the buffer is sent as-is.
EpdDisplay::EpdDisplay() : GFXcanvas1(kSize, kSize) {}

void EpdDisplay::begin() {
  pinMode(PIN_EPD_PWR, OUTPUT);
  digitalWrite(PIN_EPD_PWR, LOW);
  pinMode(PIN_EPD_CS, OUTPUT);
  digitalWrite(PIN_EPD_CS, HIGH);
  pinMode(PIN_EPD_DC, OUTPUT);
  pinMode(PIN_EPD_RST, OUTPUT);
  digitalWrite(PIN_EPD_RST, HIGH);
  pinMode(PIN_EPD_BUSY, INPUT);
  delay(10);

  epdSpi.begin(PIN_EPD_SCK, -1, PIN_EPD_MOSI, -1);
  fillScreen(kWhite);
}

void EpdDisplay::refreshFull() {
  waitBusy();
  initFull();
  writeRam(0x24);  // new image
  writeRam(0x26);  // previous image: base for partial refreshes
  update(0xC7);
  partialMode_ = false;
}

void EpdDisplay::refreshPartial() {
  waitBusy();
  if (!partialMode_) {
    initPartial();
    partialMode_ = true;
  }
  setRamArea();
  writeRam(0x24);
  update(0xCF);
}

void EpdDisplay::powerOff() {
  waitBusy();
  command(0x10);  // deep sleep
  data(0x01);
  delay(5);
  digitalWrite(PIN_EPD_PWR, HIGH);
  partialMode_ = false;
}

void EpdDisplay::reset() {
  digitalWrite(PIN_EPD_RST, HIGH);
  delay(50);
  digitalWrite(PIN_EPD_RST, LOW);
  delay(20);
  digitalWrite(PIN_EPD_RST, HIGH);
  delay(50);
  waitBusy();
}

void EpdDisplay::initFull() {
  reset();
  command(0x12);  // software reset
  waitBusy();

  command(0x01);  // driver output control: 200 gates, scan G199 -> G0
  data(0xC7);
  data(0x00);
  data(0x01);

  setRamArea();

  command(0x3C);  // border waveform
  data(0x01);
  command(0x18);  // internal temperature sensor
  data(0x80);
  command(0x22);  // load temperature + waveform
  data(0xB1);
  command(0x20);
  waitBusy();

  setLut(kLutFull);
}

void EpdDisplay::initPartial() {
  reset();
  setLut(kLutPartial);

  command(0x37);  // OTP options: enable "ping-pong" for partial mode
  const uint8_t otp[] = {0x00, 0x00, 0x00, 0x00, 0x00, 0x40, 0x00, 0x00, 0x00, 0x00};
  data(otp, sizeof(otp));

  command(0x3C);  // border waveform
  data(0x80);
  command(0x22);  // enable clock + analog
  data(0xC0);
  command(0x20);
  waitBusy();
}

// X increments, Y decrements from the last row (matches the gate scan direction).
void EpdDisplay::setRamArea() {
  command(0x11);  // data entry mode
  data(0x01);
  command(0x44);  // RAM X start/end, in bytes
  data(0x00);
  data((kSize - 1) >> 3);
  command(0x45);  // RAM Y start/end
  data((kSize - 1) & 0xFF);
  data((kSize - 1) >> 8);
  data(0x00);
  data(0x00);
  command(0x4E);  // RAM X counter
  data(0x00);
  command(0x4F);  // RAM Y counter
  data((kSize - 1) & 0xFF);
  data((kSize - 1) >> 8);
}

void EpdDisplay::setLut(const uint8_t *lut) {
  command(0x32);
  data(lut, 153);
  waitBusy();
  command(0x3F);
  data(lut[153]);
  command(0x03);  // gate voltage
  data(lut[154]);
  command(0x04);  // source voltage
  data(&lut[155], 3);
  command(0x2C);  // VCOM
  data(lut[158]);
}

void EpdDisplay::writeRam(uint8_t cmd) {
  command(cmd);
  data(getBuffer(), kBufferLen);
}

// Starts the display update and returns without waiting for it.
void EpdDisplay::update(uint8_t mode) {
  command(0x22);
  data(mode);
  command(0x20);
}

bool EpdDisplay::isBusy() const {
  return digitalRead(PIN_EPD_BUSY) == HIGH;
}

void EpdDisplay::waitBusy() {
  const uint32_t start = millis();
  while (isBusy()) {
    if (millis() - start > kBusyTimeoutMs) {
      LOGE("epd", "e-paper busy timeout");
      return;
    }
    delay(5);
  }
}

void EpdDisplay::command(uint8_t cmd) {
  epdSpi.beginTransaction(SPISettings(kSpiHz, MSBFIRST, SPI_MODE0));
  digitalWrite(PIN_EPD_DC, LOW);
  digitalWrite(PIN_EPD_CS, LOW);
  epdSpi.write(cmd);
  digitalWrite(PIN_EPD_CS, HIGH);
  epdSpi.endTransaction();
}

void EpdDisplay::data(uint8_t value) {
  data(&value, 1);
}

void EpdDisplay::data(const uint8_t *values, size_t len) {
  epdSpi.beginTransaction(SPISettings(kSpiHz, MSBFIRST, SPI_MODE0));
  digitalWrite(PIN_EPD_DC, HIGH);
  digitalWrite(PIN_EPD_CS, LOW);
  epdSpi.writeBytes(values, len);
  digitalWrite(PIN_EPD_CS, HIGH);
  epdSpi.endTransaction();
}
